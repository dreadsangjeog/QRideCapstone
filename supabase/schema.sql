create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.bikes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  label text,
  status text not null default 'available' check (status in ('available','rented','maintenance')),
  photo_path text,
  created_at timestamptz not null default now()
);

create table if not exists public.rentals (
  id uuid primary key default gen_random_uuid(),
  bike_id uuid references public.bikes(id) on delete set null,
  user_id uuid not null references auth.users(id),
  status text not null default 'active' check (status in ('active','ended')),
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create index if not exists rentals_status_started_at_idx on public.rentals(status, started_at desc);
create index if not exists rentals_user_id_started_at_idx on public.rentals(user_id, started_at desc);
create index if not exists rentals_bike_id_idx on public.rentals(bike_id);

create table if not exists public.rental_locations (
  id bigint generated by default as identity primary key,
  rental_id uuid not null references public.rentals(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision,
  recorded_at timestamptz not null default now()
);

create index if not exists rental_locations_rental_time_idx
  on public.rental_locations(rental_id, recorded_at desc);

create table if not exists public.rental_last_location (
  rental_id uuid primary key references public.rentals(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  lat double precision not null,
  lng double precision not null,
  accuracy_m double precision,
  recorded_at timestamptz not null
);

create index if not exists rental_last_location_user_idx
  on public.rental_last_location(user_id);

