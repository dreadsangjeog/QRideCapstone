-- rental_locations: insert only for own active rental; read own or admin
drop policy if exists "rental_locations_select" on public.rental_locations;
create policy "rental_locations_select"
  on public.rental_locations for select
  to authenticated
  using (
    public.is_admin()
    or user_id = auth.uid()
  );

drop policy if exists "rental_locations_insert_own_active" on public.rental_locations;
create policy "rental_locations_insert_own_active"
  on public.rental_locations for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and public.user_has_active_rental(rental_id)
  );

-- rental_last_location: upsert semantics handled by insert+update policies
drop policy if exists "rental_last_location_select" on public.rental_last_location;
create policy "rental_last_location_select"
  on public.rental_last_location for select
  to authenticated
  using (
    public.is_admin()
    or user_id = auth.uid()
  );

drop policy if exists "rental_last_location_insert" on public.rental_last_location;
create policy "rental_last_location_insert"
  on public.rental_last_location for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and public.user_has_active_rental(rental_id)
  );

drop policy if exists "rental_last_location_update" on public.rental_last_location;
create policy "rental_last_location_update"
  on public.rental_last_location for update
  to authenticated
  using (
    user_id = auth.uid()
    and public.user_has_active_rental(rental_id)
  )
  with check (
    user_id = auth.uid()
    and public.user_has_active_rental(rental_id)
  );

