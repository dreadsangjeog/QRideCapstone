create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select (p.role = 'admin') from public.profiles p where p.id = auth.uid()),
    false
  );
$$;

-- True if the given rental belongs to auth.uid() and is active
create or replace function public.user_has_active_rental(p_rental_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.rentals r
    where r.id = p_rental_id
      and r.user_id = auth.uid()
      and r.status = 'active'
  );
$$;

-- Signup: true if this email already belongs to a confirmed auth user (blocks duplicate Gmail).
create or replace function public.signup_email_already_confirmed(check_email text)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from auth.users u
    where lower(trim(u.email)) = lower(trim(check_email))
      and u.email_confirmed_at is not null
  );
$$;

revoke all on function public.signup_email_already_confirmed(text) from public;
grant execute on function public.signup_email_already_confirmed(text) to anon, authenticated;

-- True if auth.users already has this email (any confirmation state).
create or replace function public.signup_auth_email_taken(check_email text)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from auth.users u
    where lower(trim(u.email)) = lower(trim(check_email))
  );
$$;

revoke all on function public.signup_auth_email_taken(text) from public;
grant execute on function public.signup_auth_email_taken(text) to anon, authenticated;

