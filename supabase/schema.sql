create or replace function public.prune_rental_locations_older_than_7_days()
returns integer
language sql
security definer
set search_path = public
as $$
  with deleted as (
    delete from public.rental_locations
    where recorded_at < (now() - interval '7 days')
    returning 1
  )
  select count(*)::integer from deleted;
$$;

