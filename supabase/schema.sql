create or replace function public.start_rental_for_bike(p_bike_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rental_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  update public.bikes
  set status = 'rented'
  where id = p_bike_id
    and status = 'available';

  if not found then
    raise exception 'Bike is not available';
  end if;

  insert into public.rentals (bike_id, user_id, status)
  values (p_bike_id, auth.uid(), 'active')
  returning id into v_rental_id;

  return v_rental_id;
end;
$$;

grant execute on function public.start_rental_for_bike(uuid) to authenticated;

create or replace function public.end_rental_for_user(p_rental_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_bike_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Not authenticated';
  end if;

  update public.rentals
  set status = 'ended',
      ended_at = now()
  where id = p_rental_id
    and user_id = auth.uid()
    and status = 'active'
  returning bike_id into v_bike_id;

  if v_bike_id is null then
    raise exception 'Active rental not found';
  end if;

  delete from public.rental_last_location where rental_id = p_rental_id;

  update public.bikes
  set status = 'available'
  where id = v_bike_id;
end;
$$;

grant execute on function public.end_rental_for_user(uuid) to authenticated;

