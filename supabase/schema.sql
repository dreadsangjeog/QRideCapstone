create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_username text;
begin
  v_username := nullif(trim(lower(coalesce(new.raw_user_meta_data->>'username', ''))), '');
  if v_username is not null then
    -- auth.users does not have a `display_name` column. Store a friendly name in user metadata instead.
    update auth.users
    set raw_user_meta_data = coalesce(raw_user_meta_data, '{}'::jsonb)
      || jsonb_build_object('name', v_username, 'full_name', v_username)
    where id = new.id;
  end if;
  insert into public.profiles (id, username)
  values (new.id, v_username)
  on conflict (id) do update set username = excluded.username
  where excluded.username is not null;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create unique index if not exists profiles_username_lower_unique
  on public.profiles (lower(trim(username)))
  where username is not null and trim(username) <> '';

-- Keep auth.users user metadata in sync so it shows in Authentication → Users
create or replace function public.sync_auth_user_metadata_from_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update auth.users
  set raw_user_meta_data = coalesce(raw_user_meta_data, '{}'::jsonb)
    || jsonb_build_object('name', new.username, 'full_name', new.username)
  where id = new.id
    and new.username is not null
    and trim(new.username) <> '';
  return new;
end;
$$;

drop trigger if exists profiles_sync_auth_display_name on public.profiles;
drop trigger if exists profiles_sync_auth_user_metadata on public.profiles;
create trigger profiles_sync_auth_user_metadata
  after insert or update of username on public.profiles
  for each row
  execute function public.sync_auth_user_metadata_from_profile();

