-- 1. GPS history table (full track log)
create table if not exists public.rental_locations (
  id          bigint generated by default as identity primary key,
  rental_id   uuid not null references public.rentals(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  lat         double precision not null,
  lng         double precision not null,
  accuracy_m  double precision,
  recorded_at timestamptz not null default now()
);

create index if not exists rental_locations_rental_time_idx
  on public.rental_locations(rental_id, recorded_at desc);

-- 2. Last-known location table (one row per rental, upserted each GPS fix)
create table if not exists public.rental_last_location (
  rental_id   uuid primary key references public.rentals(id) on delete cascade,
  user_id     uuid not null references auth.users(id) on delete cascade,
  lat         double precision not null,
  lng         double precision not null,
  accuracy_m  double precision,
  recorded_at timestamptz not null
);

create index if not exists rental_last_location_user_idx
  on public.rental_last_location(user_id);

-- 3. Helper function used by RLS policies
create or replace function public.user_has_active_rental(p_rental_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.rentals r
    where r.id = p_rental_id
      and r.user_id = auth.uid()
      and r.status = 'active'
  );
$$;

-- 4. Enable RLS on both tables
alter table public.rental_locations        enable row level security;
alter table public.rental_last_location    enable row level security;

-- 5. RLS policies for rental_locations
drop policy if exists "rental_locations_select"             on public.rental_locations;
drop policy if exists "rental_locations_insert_own_active"  on public.rental_locations;

create policy "rental_locations_select"
  on public.rental_locations for select
  to authenticated
  using (public.is_admin() or user_id = auth.uid());

create policy "rental_locations_insert_own_active"
  on public.rental_locations for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and public.user_has_active_rental(rental_id)
  );

-- 6. RLS policies for rental_last_location (upsert = insert + update)
drop policy if exists "rental_last_location_select"  on public.rental_last_location;
drop policy if exists "rental_last_location_insert"  on public.rental_last_location;
drop policy if exists "rental_last_location_update"  on public.rental_last_location;

create policy "rental_last_location_select"
  on public.rental_last_location for select
  to authenticated
  using (public.is_admin() or user_id = auth.uid());

create policy "rental_last_location_insert"
  on public.rental_last_location for insert
  to authenticated
  with check (
    user_id = auth.uid()
    and public.user_has_active_rental(rental_id)
  );

create policy "rental_last_location_update"
  on public.rental_last_location for update
  to authenticated
  using  (user_id = auth.uid() and public.user_has_active_rental(rental_id))
  with check (user_id = auth.uid() and public.user_has_active_rental(rental_id));

